#!/usr/bin/env python3
# Usage: ext_map.py <agent dir> <public bali-cases.json> <out kbx_j_map.js>
# Builds _worker.js/kbx_j_map.js (kolaboro.com browser extension overlay): hashed lookup keys (portal listing address, project name) -> anonymous project id.
# Reads the agent's private project files (read only). IDs are derived exactly as agent.py public_cases() does, and
# cross-checked against the public dataset. Only hashes are stored, never addresses or names.
import json, re, sys, hashlib, unicodedata, collections
AG = sys.argv[1]; PUB = sys.argv[2]; OUT = sys.argv[3]
src = open(AG + '/agent.py').read()
PREFIX = eval(re.search(r"PREFIX = (\{.*?\})\n", src, re.S).group(1))
P = json.load(open(AG + '/projects.json'))['projects'] + json.load(open(AG + '/projects-world.json'))['projects']
n = {}; ids = {}
for p in sorted(P, key=lambda x: x.get('market', 'Bali') != 'Bali'):
    mk = p.get('market', 'Bali'); n[mk] = n.get(mk, 0) + 1
    ids[p['slug']] = '%s-%03d' % (PREFIX.get(mk, mk[:3].upper()), n[mk])
pub = {c['id']: c for c in json.load(open(PUB))['cases']}
bad = [p['slug'] for p in P if not (pub.get(ids[p['slug']]) and pub[ids[p['slug']]]['market'] == p.get('market', 'Bali') and pub[ids[p['slug']]]['country'] == p.get('country', 'Indonesia'))]
if bad or len(pub) != len(P):
    print('ids do not match the published dataset yet (%d mismatches, %d vs %d projects): map not rebuilt' % (len(bad), len(P), len(pub))); sys.exit(0)

# portals whose listing addresses are kept as keys (the extension's content script runs on these)
PORTALS = r'(^|\.)(propertyfinder\.(ae|bh|eg|qa|sa)|bayut\.com|rumah123\.com|fazwaz\.(com|co\.th|id|ph|vn|my)|dotproperty\.(com\.ph|co\.th|id)|thailand-property\.com|rumavi\.com|realting\.com|emlakplatform\.com\.tr|pincali\.com|edgeprop\.my|propertyguru\.com\.my|idealista\.(com|pt)|apartments\.com\.au)$'
GENERIC = set('the by residences residence residential villas villa tower towers sky views view heights park gardens garden apartments apartment homes home house houses estate estates by at de del la el los las and of in on phase project resort hotel suites suite living city one two bay beach ocean sea hills hill marina place square point plaza grand royal new collection'.split())

def h(s): return hashlib.sha256(s.encode()).hexdigest()[:16]
def norm_name(t):
    t = unicodedata.normalize('NFKD', t).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', ' ', t).strip()
def url_key(u):
    m = re.match(r'https?://(?:www\.)?([^/?#]+)([^?#]*)', u.strip(), re.I)
    if not m: return None
    host = m.group(1).lower(); path = m.group(2).lower().rstrip('/')
    if not re.search(PORTALS, host): return None
    path = re.sub(r'^/(en|ar|id|th|es|pt|tr|ru|zh|de|fr)(?=/|$)', '', path)
    if len(path) < 8: return None   # a home or search page, not a listing
    return host + path
def ok_name(t):
    w = t.split()
    return len(w) >= 2 and len(t) >= 10 and any(x not in GENERIC and len(x) >= 4 and not x.isdigit() for x in w)
def variants(name):
    v = {name}
    v.add(re.sub(r'\s*\(.*?\)\s*', ' ', name)); v.update(re.findall(r'\((.*?)\)', name))
    for x in list(v): v.add(re.split(r'\s+by\s+', x, flags=re.I)[0])
    return {norm_name(x) for x in v if ok_name(norm_name(x))}

U = collections.defaultdict(set); N = collections.defaultdict(set)
for p in P:
    i = ids[p['slug']]
    for u in [p.get('url'), p.get('docs_url')] + list(p.get('sources') or []):
        k = url_key(u) if isinstance(u, str) else None
        if k: U[h('u|' + k)].add(i)
    for k in variants(p.get('name') or ''): N[h('n|' + k)].add(i)
u1 = {k: next(iter(v)) for k, v in sorted(U.items()) if len(v) == 1}
n1 = {k: next(iter(v)) for k, v in sorted(N.items()) if len(v) == 1}
out = {'built': json.load(open(PUB))['updated'], 'projects': len(P), 'url_keys': len(u1), 'name_keys': len(n1),
       'url_projects': len(set(u1.values())), 'name_projects': len(set(n1.values())), 'u': u1, 'n': n1}
open(OUT, 'w').write('// Generated by gen_map.py from the agent\'s private project files. Truncated SHA-256 of "u|host/path" or "n|name" -> anonymous id.\n'
                     '// Only hashes: no addresses or names are stored here. Keys mapping to more than one project are dropped.\n'
                     'export const MAP = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print({k: v for k, v in out.items() if k not in ('u', 'n')})
